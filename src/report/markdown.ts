// Deterministic report: everything we observed, no LLM. Also used as the
// appendix under an LLM-written report so every [E#] resolves to a source.
import { engines, type ChannelScore } from "../analyze/scorecard.js";
import type { EvidenceBundle } from "../index.js";

const LABEL: Record<string, string> = {
  paid_meta: "Paid · Meta",
  paid_google: "Paid · Google",
  paid_linkedin: "Paid · LinkedIn",
  paid_reddit: "Paid · Reddit",
  paid_tiktok: "Paid · TikTok",
  organic_tiktok: "Organic · TikTok",
  organic_instagram: "Organic · Instagram",
  organic_youtube: "Organic · YouTube",
  organic_x: "Organic · X",
  organic_linkedin: "Organic · LinkedIn page",
  seo: "SEO",
  geo: "AI search (GEO)",
  founder_led: "Founder-led",
  reddit_marketing: "Reddit marketing",
  community: "Community",
  launches: "Launches (HN / PH)",
  app_store: "App stores",
  lifecycle: "Lifecycle / email",
  affiliate: "Affiliate / referral",
  sales_led: "Sales-led motion",
};

const DOTS = ["○○○", "●○○", "●●○", "●●●"];

export function channelLabel(c: string): string {
  return LABEL[c] ?? c;
}

export function scorecardTable(card: ChannelScore[]): string {
  const rows = card.filter(c => c.status !== "unknown" || c.strength > 0);
  return [
    "| Channel | Status | Strength | What we saw | Evidence |",
    "|---|---|---|---|---|",
    ...rows.map(c => `| ${channelLabel(c.channel)} | ${c.status} | ${DOTS[c.strength]} | ${esc(c.signal)} | ${c.evidence.map(e => `[${e}]`).join(" ")} |`),
  ].join("\n");
}

export function evidenceAppendix(bundle: EvidenceBundle): string {
  return [
    "## Evidence",
    "",
    ...bundle.evidence.map(e => `- **[${e.id}]** ${e.kind === "derivation" ? "_(derived)_ " : ""}${esc(e.title)}${e.url ? ` — <${e.url}>` : ""}`),
  ].join("\n");
}

export function unknownsSection(bundle: EvidenceBundle): string {
  if (!bundle.unknowns.length) return "";
  return ["## Unknowns & how to check", "", ...bundle.unknowns.map(u => `- **${channelLabel(String(u.channel))}**: ${esc(u.reason)}${u.manualCheck ? ` → <${u.manualCheck}>` : ""}`)].join("\n");
}

export function renderMarkdown(bundle: EvidenceBundle, opts: { narrative?: string } = {}): string {
  const header = `<sub>Generated by [reverse-engineer-marketing](https://github.com/dansugc/reverse-engineer-marketing) v${bundle.tool.version} · harness v${bundle.harness.version} (${bundle.harness.sha}) · ${bundle.generatedAt.slice(0, 10)}${bundle.credits.scrapecreators != null ? ` · ${bundle.credits.scrapecreators} Scrape Creators credits` : ""}</sub>`;
  if (opts.narrative) return [opts.narrative.trim(), "", "---", "", evidenceAppendix(bundle), "", header, ""].join("\n");

  const top = engines(bundle.scorecard);
  const ev = (src: string) => bundle.evidence.filter(e => e.source === src);
  const section = (title: string, sources: string[]) => {
    const items = sources.flatMap(ev);
    if (!items.length) return "";
    return [`## ${title}`, "", ...items.map(e => `### ${esc(e.title)} [${e.id}]\n\n${e.url ? `<${e.url}>\n\n` : ""}${details(e.data)}`)].join("\n");
  };
  return [
    `# How ${bundle.brand} gets customers`,
    "",
    header,
    "",
    top.length ? `**Likely engines:** ${top.map(c => `${channelLabel(c.channel)} (${c.signal})`).join(" · ")}` : "**Likely engines:** not enough evidence — see unknowns.",
    "",
    "> Raw evidence report (no AI). Run with `ANTHROPIC_API_KEY` set for the written strategy, or connect the MCP server and let your agent write it.",
    "",
    "## Channel scorecard",
    "",
    scorecardTable(bundle.scorecard),
    "",
    section("Website, offer & funnel", ["website", "tracking"]),
    section("Paid", ["meta_ads", "google_ads", "linkedin_ads", "reddit_ads"]),
    section("Organic social", ["tiktok", "instagram", "youtube", "x", "linkedin", "threads"]),
    section("SEO & AI search", ["seo"]),
    section("Founders & people", ["founders", "wikidata"]),
    section("Community & launches", ["reddit", "hackernews", "producthunt"]),
    section("Apps", ["appstore"]),
    section("Positioning over time", ["wayback"]),
    unknownsSection(bundle),
    "",
  ]
    .filter(s => s !== "")
    .join("\n\n");
}

function details(data: unknown): string {
  const json = JSON.stringify(data, null, 2);
  const body = json.length > 6000 ? `${json.slice(0, 6000)}\n…` : json;
  return `<details><summary>data</summary>\n\n\`\`\`json\n${body}\n\`\`\`\n\n</details>`;
}

function esc(s: string): string {
  return s.replace(/\|/g, "\\|").replace(/\n/g, " ");
}
